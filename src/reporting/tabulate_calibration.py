"""Print Tables 7 and 8 (operating point and calibration by tone).

Run:    python -m src.reporting.tabulate_calibration [operating|calibration]
"""
import io
import json
import os
import sys

REPO = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))
C = json.load(io.open(os.path.join(REPO, 'results', 'calibration_operating_point.json'),
                      encoding='utf-8'))

LABEL = {'erm': 'ERM', 'gdro_tuned': 'Group-DRO', 'resample': 'Resample',
         'reweight': 'Reweight', 'dfr': 'DFR', 'afr': 'AFR', 'dpe': 'DPE',
         'mono_global': '+ mono', 'reweight_mono': 'reweight + mono'}
OURS = ('mono_global', 'reweight_mono')
GROUPS = ('light', 'mid', 'dark')


def pct(v):
    return '%.1f' % (100 * v)


def rows(fn):
    for m in C['method_order']:
        if m == OURS[0]:
            print('  \\midrule')
        print('  %-16s & %s \\\\' % (LABEL[m], ' & '.join('$%s$' % c for c in fn(C['methods'][m]))))


def emit_operating():
    print('% --- generated by tabulate_calibration.py operating; do not hand-edit ---')
    print('% columns: shared threshold sens light/mid/dark, spec light/mid/dark | '
          'per-tone threshold sens light/mid/dark')
    rows(lambda r: [pct(r['shared_threshold'][g]['sensitivity']['mean']) for g in GROUPS]
         + [pct(r['shared_threshold'][g]['specificity']['mean']) for g in GROUPS]
         + [pct(r['pergroup_threshold'][g]['sensitivity']['mean']) for g in GROUPS])
    spec = [r['pergroup_threshold'][g]['specificity']['mean']
            for r in C['methods'].values() for g in GROUPS]
    print('%% per-tone thresholds: specificity %s-%s%% across all methods and tones'
          % (pct(min(spec)), pct(max(spec))))
    n = C['test_counts']
    print('%% test images (malignant): %s'
          % ', '.join('%s %d (%d)' % (g, n[g]['n'], n[g]['n_malignant']) for g in GROUPS))


def emit_calibration():
    print('% --- generated by tabulate_calibration.py calibration; do not hand-edit ---')
    print('% columns: recalibrated ECE light/mid/dark | perfect-calibration ECE, dark | '
          'observed/expected light/mid/dark | z, dark minus light')

    def cells(r):
        cl = r['calibration_in_the_large']
        return ([pct(r['ece_platt'][g]['mean']) for g in GROUPS]
                + [pct(r['ece_platt_null']['dark']['mean'])]
                + ['%.2f' % cl[g]['observed_over_expected']['mean'] for g in GROUPS]
                + ['%+.2f' % r['dark_vs_light']['z']['mean']])
    rows(cells)
    raw = {g: [r['ece_raw'][g]['mean'] for r in C['methods'].values()] for g in GROUPS}
    print('%% raw ECE before recalibration, range over methods: %s'
          % ', '.join('%s %s-%s' % (g, pct(min(v)), pct(max(v))) for g, v in raw.items()))
    print('% seeds (of 10) with recalibrated dark ECE above the 95th percentile of the '
          'perfect-calibration baseline: '
          + ', '.join('%s %d' % (LABEL[m], C['methods'][m]['seeds_ece_above_null_p95']['dark'])
                      for m in C['method_order']))
    print('% seeds (of 10) with dark-minus-light z above 1.96: '
          + ', '.join('%s %d' % (LABEL[m], C['methods'][m]['dark_vs_light']['seeds_z_above_crit'])
                      for m in C['method_order']))


WHICH = {'operating': emit_operating, 'calibration': emit_calibration}

if __name__ == '__main__':
    for k in (sys.argv[1:] or list(WHICH)):
        WHICH[k]()
        print()
