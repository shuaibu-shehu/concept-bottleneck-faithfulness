"""Print the concept tables: layers (Table 2), prompts (Table 3), concepts (Table 4),
sign agreement (Table 5) and the sign rule (Table 6).

Run:    python -m src.reporting.tabulate_concepts [signs|prompts|concepts|signrule|signagree|layers]
"""
import io
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, '..', '..'))

from src.concept_layer import CLINICAL_SIGNS, MIN_POSITIVES
from src.prompts import CONCEPT_PROMPTS

LAY = os.path.join(REPO, 'results/concept_layer.json')
CSV = os.path.join(REPO, 'data/skincon_fitz.csv')

# two SkinCon names shortened for the table
PRETTY = {'Brown(Hyperpigmentation)': 'Brown (hyperpigmentation)',
          'White(Hypopigmentation)': 'White (hypopigmentation)'}

# the checklist criterion each prompt pair scores, spelled as a dermatologist would
CRITERION = {'atypical_pigment_network': 'Atypical pigment network',
             'blue_whitish_veil': 'Blue-whitish veil',
             'atypical_vascular': 'Atypical vascular structures',
             'irregular_streaks': 'Irregular streaks',
             'irregular_pigmentation': 'Irregular pigmentation',
             'irregular_dots_globules': 'Irregular dots and globules',
             'regression': 'Regression structures'}


def tex(s):
    return s.replace('&', '\\&').replace('_', '\\_').replace('%', '\\%')


def name(c):
    return tex(PRETTY.get(c, c))


def emit_signs():
    order = {1: [], -1: [], 0: []}
    for c, s in CLINICAL_SIGNS.items():
        order[s].append(name(c))
    # two columns, so a long concept list fits a single-column table
    lbl = {1: '+1', -1: '-1', 0: '\\phantom{+}0'}
    print('% --- generated by tabulate_concepts.py signs ---')
    for sign in (1, -1, 0):
        cs = order[sign]
        print('  $%s$ (%d) & %s \\\\[2pt]' % (lbl[sign], len(cs), ', '.join(cs)))


PROMPT_STEM = 'a skin lesion '


def emit_prompts():
    """Table 3: the prompt pairs, with the shared stem moved to the caption."""
    print('% --- generated by tabulate_concepts.py prompts ---')
    for concept, (pos, neg) in CONCEPT_PROMPTS.items():
        assert pos.startswith(PROMPT_STEM) and neg.startswith(PROMPT_STEM), concept
        print('  %s & \\emph{%s} & \\emph{%s} \\\\'
              % (tex(CRITERION[concept]), tex(pos[len(PROMPT_STEM):]),
                 tex(neg[len(PROMPT_STEM):])))


def load(name_):
    return json.load(io.open(os.path.join(REPO, 'results', name_), encoding='utf-8'))


def emit_concepts():
    lay = json.load(io.open(LAY, encoding='utf-8'))
    det = lay['detection']
    # prompt detection for the same concepts, against the same held-out annotations
    single = load('zeroshot_vocabulary.json')['detection']['zeroshot22']
    ens = load('prompt_ensemble.json')['detection']['ensemble']
    print('% --- generated by tabulate_concepts.py concepts ---')
    print('% columns: concept, sign, positives, probe AUROC all/light/mid/dark, '
          'prompt AUROC one pair/ensemble')
    # rows grouped by sign (+1, -1, unsigned), in JSON order within each group
    order = sorted(lay['concepts'], key=lambda c: {1: 0, -1: 1, 0: 2}[det[c]['sign']])
    for c in order:
        d = det[c]
        s = {1: '$+1$', -1: '$-1$', 0: '--'}[d['sign']]
        print('  %-28s & %s & %5d & %.3f & %.3f & %.3f & %.3f & %.3f & %.3f \\\\'
              % (name(c), s, d['n_pos_labelled'], d['auroc_all'], d['auroc_light'],
                 d['auroc_mid'], d['auroc_dark'], single[c]['auroc_all'],
                 ens[c]['auroc_all']))

    def mean_of(src, key):
        return sum(src[c][key] for c in order) / len(order)
    print('  \\midrule')
    print('  %-28s & & & %.3f & %.3f & %.3f & %.3f & %.3f & %.3f \\\\'
          % ('Mean', mean_of(det, 'auroc_all'), mean_of(det, 'auroc_light'),
             mean_of(det, 'auroc_mid'), mean_of(det, 'auroc_dark'),
             mean_of(single, 'auroc_all'), mean_of(ens, 'auroc_all')))
    print('%% mean detection: probe %.3f | one prompt pair %.3f (%d below 0.5) | '
          'ensemble %.3f (%d below 0.5)'
          % (sum(det[c]['auroc_all'] for c in order) / len(order),
             sum(single[c]['auroc_all'] for c in order) / len(order),
             sum(single[c]['auroc_all'] < 0.5 for c in order),
             sum(ens[c]['auroc_all'] for c in order) / len(order),
             sum(ens[c]['auroc_all'] < 0.5 for c in order)))
    # correlations of prompt detection with probe detection and prevalence (Appendix B)
    import numpy as np
    probe_auc = [det[c]['auroc_all'] for c in order]
    n_pos = [det[c]['n_pos_labelled'] for c in order]
    for label, src in (('one-pair', single), ('ensemble', ens)):
        z = np.array([src[c]['auroc_all'] for c in order])
        print('%% Pearson r across concepts: %s prompt detection vs probe detection %+.2f, '
              'vs prevalence %+.2f'
              % (label, np.corrcoef(z, probe_auc)[0, 1], np.corrcoef(z, n_pos)[0, 1]))
    # per-tone means of prompt detection (Appendix B)
    for label, src in (('probe', det), ('one pair', single), ('ensemble', ens)):
        print('%% mean detection by tone, %s: %s'
              % (label, ', '.join('%s %.3f' % (k, np.mean([src[c]['auroc_' + k] for c in order]))
                                  for k in ('light', 'mid', 'dark'))))

    # concepts dropped by the 50-positive threshold, with their counts
    import pandas as pd
    df = pd.read_csv(CSV)
    meta = ('Unnamed: 0', 'ImageID', 'md5hash', 'DDI_file',
            'Do not consider this image')
    kept = set(lay['concepts'])
    pos = df[[c for c in df.columns if c not in meta]].sum().astype(int)
    dropped = pos[[c for c in pos.index if c not in kept]].sort_values(ascending=False)
    print()
    print('%% dropped by the >= %d positives rule (%d concepts), counts over the '
          'annotation file:' % (MIN_POSITIVES, len(dropped)))
    print('% ' + ', '.join('%s~%d' % (name(c), v) for c, v in dropped.items()))


def emit_signrule():
    """Table 6: rows 1-2 change only the directions, rows 2-3 only the concept set."""
    S = json.load(io.open(os.path.join(REPO, 'results/faithfulness_gap_supervised.json'),
                          encoding='utf-8'))['sets']
    rows = [('clinical \\emph{(primary)}', 14, 'clinical'),
            ('derived', 14, 'derived14'),
            ('derived', 22, 'derived')]
    print('% --- generated by tabulate_concepts.py signrule ---')
    for label, n, key in rows:
        cells = []
        for pre in ('fitz_oof__', 'ddi_external__'):
            r = S[pre + key]
            lo, hi = r['ci_on_mean_gap']['lo'], r['ci_on_mean_gap']['hi']
            cells += ['$%.4f$' % r['gap_mean'], '$[%.4f, %.4f]$' % (lo, hi),
                      'yes' if lo > 0 or hi < 0 else 'no']
        print('  %-24s & $%d$ & %s \\\\' % (label, n, ' & '.join(cells)))

    c, d14, d = [S['fitz_oof__' + k]['gap_mean']
                 for k in ('clinical', 'derived14', 'derived')]
    tot = d - c
    print()
    print('%% decomposition on Fitzpatrick: total %.4f = signs %.4f (%.1f%%) '
          '+ concept set %.4f (%.1f%%)'
          % (tot, d14 - c, 100 * (d14 - c) / tot, d - d14, 100 * (d - d14) / tot))


def emit_signagree():
    """Each declared sign against the direction the training labels imply, per fold."""
    A = load('sign_agreement.json')
    print('% --- generated by tabulate_concepts.py signagree ---')
    print('% columns: concept, clinical sign, folds where the derived sign agrees, '
          'train AUROC of the concept score against malignancy')
    for r in sorted(A['concepts'], key=lambda r: (r['agrees'], -r['clinical_sign'])):
        print('  %-28s & $%+d$ & %d/%d & %.3f \\\\'
              % (name(r['concept']), r['clinical_sign'], r['folds_agreeing'],
                 r['n_folds'], r['auroc_vs_malignancy_train']))
    print('%% agree on %d of %d; one-sided exact binomial p against arbitrary signs = %.4f'
          % (A['n_agree'], A['n_signed'], A['binomial_p_one_sided']))


def emit_layers():
    """Table 2: concept layers compared by vocabulary and readout.

    AUROC and its gap come from one logistic regression per feature set; the monotonicity gap
    is the primary endpoint (two-layer head, 20 seeds, out of fold).
    """
    rc = load('readout_comparison.json')['results']
    det = load('prompt_ensemble.json')['detection']['mean_auroc']
    zs = load('faithfulness_gap_zeroshot.json')['sets']['fitz_oof']
    sv = load('faithfulness_gap_supervised.json')['sets']['fitz_oof__clinical']
    pl = load('faithfulness_gap_prompt_layers.json')['layers']
    # short labels: the table sits in one column of a two-column page
    rows = [('raw embedding (512-d)', 'embedding', '--', None, None),
            ('7 unsupervised PCA', 'PCA (7)', '--', None, None),
            ('22 unsupervised PCA', 'PCA (22)', '--', None, None),
            ('7 zero-shot checklist', 'checklist (7)', '1 pair', None, zs),
            ('22 zero-shot SkinCon', 'SkinCon (22)', '1 pair',
             det['single_pair'], pl['skincon_single_prompt']['fitz_oof']),
            ('22 zero-shot SkinCon ensemble', 'SkinCon (22)', '6 pairs',
             det['ensemble'], pl['skincon_prompt_ensemble']['fitz_oof']),
            ('22 supervised SkinCon', 'SkinCon (22)', 'probes',
             det['supervised'], sv)]
    print('% --- generated by tabulate_concepts.py layers ---')
    print('% columns: feature set, readout, concept detection, AUROC, light-dark AUROC gap '
          '(Section 5.1 estimator), monotonicity gap (endpoint protocol)')
    # the CIs are printed as comments, since they do not fit the column
    cis = []
    for key, feature_set, readout, d, gap in rows:
        if key == '7 zero-shot checklist':
            print('  \\midrule')
        r = rc[key]
        cells = [feature_set, readout, '--' if d is None else '$%.3f$' % d,
                 '$%.3f$' % r['auroc'], '$%+.3f$' % r['gap']]
        if gap is None:
            cells += ['--']
        else:
            c = gap['ci_on_mean_gap']
            cells += ['$%+.4f$' % gap['gap_mean']]
            cis.append('%s, %s: [%+.4f, %+.4f]' % (feature_set, readout, c['lo'], c['hi']))
        print('  %s \\\\' % ' & '.join(cells))
    for line in cis:
        print('%% 95%% CI %s' % line)


WHICH = {'signs': emit_signs, 'prompts': emit_prompts, 'concepts': emit_concepts,
         'signrule': emit_signrule, 'signagree': emit_signagree, 'layers': emit_layers}

if __name__ == '__main__':
    for k in (sys.argv[1:] or list(WHICH)):
        WHICH[k]()
        print()
