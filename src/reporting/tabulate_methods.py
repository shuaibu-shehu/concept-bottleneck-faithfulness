"""Print Table 1 from method_comparison.json.

Values are percentages, mean over seeds +- one standard deviation. Tone-specific cells
refer to dark skin.

Run:    python -m src.reporting.tabulate_methods
"""
import json

import os

import numpy as np

REPO = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                    '..', '..'))
J = json.load(open(REPO + '/results/method_comparison.json', encoding='utf-8'))

LABEL = {'erm': 'ERM', 'gdro_tuned': 'Group-DRO', 'resample': 'Resample',
         'reweight': 'Reweight', 'dfr': 'DFR', 'afr': 'AFR', 'dpe': 'DPE',
         'mono_global': '+ mono', 'reweight_mono': 'reweight + mono'}
OURS = ('mono_global', 'reweight_mono')
GROUPS = ('light', 'mid', 'dark')

# (accessor, subkey, higher-is-better, is a monotonicity column?)
#   True: largest is best; None: closest to zero is best; False: no cell is marked
COLS = [
    # accuracy
    ('test_worst_auc', None, True, False),
    ('test_auc_gap', None, None, False),
    ('sens@spec_global_thr', 'dark', True, False),
    ('ddi_auc', 'dark', False, False),
    # DDI light-dark gap: not marked, since both values are near chance
    ('ddi_auc_gap', None, False, False),
    ('derm7pt_melanoma_auc', None, True, False),
    # monotonicity
    ('test_mono', 'dark', True, True),
    ('ddi_mono', 'dark', True, True),
    ('derm7pt_mono', None, True, True),
]
N_ACC = 6


def cell(rec, key, sub, per_seed):
    """Mean and SD over seeds; averages over tones use the per-seed values."""
    if key == 'ddi_mono_mean' and key not in rec:
        vals = [rec['ddi_mono'][g]['mean'] for g in GROUPS]
        seeds = per_seed.get('ddi_mono_mean')
        return float(np.mean(vals)), (float(np.std(seeds)) if seeds else float('nan'))
    v = rec[key]
    if sub:
        v = v[sub]
    return v['mean'], v.get('sd', float('nan'))


rows = {m: [cell(J['methods'][m], k, s, J['per_seed'][m]) for k, s, _b, _f in COLS]
        for m in J['method_order']}

# Bold marks the best value per column, with ties judged at the printed precision.
# The DDI accuracy columns are not marked: every method is below chance there.
best = []
for i, (_k, _s, higher, _f) in enumerate(COLS):
    if higher is False:
        best.append(set())
        continue
    key = {m: round(rows[m][i][0] * 100, 1) for m in rows}
    target = (min(key.values(), key=abs) if higher is None else max(key.values()))
    best.append({m for m in key if key[m] == target})


def fmt(mean, sd):
    pct = '%.1f' % (mean * 100)
    return pct if np.isnan(sd) else '%s \\pm %.1f' % (pct, sd * 100)


print('% --- generated by tabulate_methods.py; do not hand-edit ---')
for m in J['method_order']:
    if m == OURS[0]:
        print('  \\midrule')
    cells = []
    for i, (mean, sd) in enumerate(rows[m]):
        t = fmt(mean, sd)
        mark = m in best[i]
        cells.append(('$\\mathbf{%s}$' if mark else '$%s$') % t)
    print('  %-16s & %s \\\\' % (LABEL[m], ' & '.join(cells)))

print()
print('% DDI light-dark AUROC gap (percentage points):')
for m in J['method_order']:
    g = J['methods'][m].get('ddi_auc_gap')
    if g is None:
        d = J['methods'][m]['ddi_auc']
        print('%%   %-16s %.1f' % (m, (d['light']['mean'] - d['dark']['mean']) * 100))
    else:
        print('%%   %-16s %.1f +- %.1f' % (m, g['mean'] * 100, g['sd'] * 100))
